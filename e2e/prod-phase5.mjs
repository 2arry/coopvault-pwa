// Production smoke check for Phase 5 (read-only: pays nothing, replies to nothing, adds nobody).
import { PROD as env, suite, page, go, launch } from './lib.mjs'

const t = suite(process.argv[2] || 'shots/prod-phase5')
const b = await launch()
const chioma = await page(b, env, t, 'chioma')
await go(chioma, env, '/home', 1500)
t.check('savings by product on Home', await chioma.getByText('Christmas savings').first().isVisible())
t.check('next meeting on Home', await chioma.getByText('November general meeting').isVisible())
await t.shot(chioma, 'p1-chioma-home')
await go(chioma, env, '/save?product=', 1200)
t.check('products to save into', await chioma.getByRole('button', { name: 'Retirement fund' }).isVisible())
await go(chioma, env, '/pay', 1500)
t.check('pay what’s due opens', await chioma.getByRole('heading', { name: /Pay what’s due/ }).isVisible())
await t.shot(chioma, 'p2-pay-due')
const ngozi = await page(b, env, t, 'ngozi')
await go(ngozi, env, '/withdraw', 1500)
t.check('retirement fund locked until leaving', await ngozi.getByText(/when you leave/).first().isVisible())
await t.shot(ngozi, 'p3-withdraw')
const sade = await page(b, env, t, 'sade')
await go(sade, env, '/meetings', 1500)
t.check('secretary sees meetings', await sade.getByText('Call a meeting').isVisible() && await sade.getByText('October general meeting').isVisible())
await sade.getByText('October general meeting').click()
await sade.waitForTimeout(1500)
t.check('published minutes on production', await sade.getByText('Resolutions').isVisible())
await t.shot(sade, 'p4-minutes')
const amaka = await page(b, env, t, 'amaka')
await go(amaka, env, '/admin?tab=members', 1500)
t.check('admins can add members', await amaka.getByText('Add a member').isVisible())
await go(amaka, env, '/admin?tab=settings', 1500)
t.check('savings products in settings', await amaka.getByText('Savings products').isVisible())
await b.close()
t.done()
