// Production smoke check for the platform console (read-only: approves, pauses and pays nothing).
import { PROD as env, suite, page, go, launch } from './lib.mjs'

const t = suite(process.argv[2] || 'shots/prod-platform')
const b = await launch()
const ops = await page(b, env, t, 'ops')
await go(ops, env, '/home', 1800)
t.check('the operator lands on the console', ops.url().includes('/platform') && await ops.getByRole('heading', { name: 'Platform console' }).isVisible())
const queued = ops.getByRole('link', { name: /Computer Village Traders Thrift/ }).first()
t.check('Computer Village waits for review', await queued.isVisible())
await t.shot(ops, 'p1-console')
await queued.click()
await ops.waitForTimeout(1500)
t.check('group page shows contacts and plan, no money', await ops.getByText('Who runs it').isVisible() && !(await ops.getByText(/Your savings|The pool|Out on loan|Saved by/i).count()))
await t.shot(ops, 'p2-group')
await go(ops, env, '/platform?tab=plans', 1500)
t.check('plans on production', await ops.getByText('Enterprise').first().isVisible())
const amaka = await page(b, env, t, 'amaka')
await go(amaka, env, '/admin/plan', 1800)
t.check('Unity is on Growth, paid ahead', await amaka.getByText('Growth').first().isVisible() && await amaka.getByText(/Paid until/).isVisible())
await t.shot(amaka, 'p3-unity-plan')
const kunle = await page(b, env, t, 'kunle')
await go(kunle, env, '/home', 1800)
t.check('the founder sees the review card', await kunle.getByText(/Cooperative360 is checking/).isVisible())
await t.shot(kunle, 'p4-founder')
await b.close()
t.done()
